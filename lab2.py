import numpy as np

# 1. Створіть одновимірний масив з 200 випадкових чисел від -100 до 100.
# Вказуємо 101, бо верхня межа в NumPy не включається
array = np.random.randint(-100, 101, size=200)

print("1. Початковий масив (показуємо перші 20 чисел):")
print(array[:20])
print("-" * 50)

# 2. Використовуючи маску, відфільтруйте всі додатні числа в масиві.
# Створюємо маску (умову) і застосовуємо її до масиву
positive_mask = array > 0
positive_numbers = array[positive_mask]

print(f"2. Додатні числа (знайдено {len(positive_numbers)} шт.). Показуємо перші 10:")
print(positive_numbers[:10])
print("-" * 50)

# 3. Замініть всі від’ємні значення на нулі.
# Це робиться дуже просто за допомогою ще однієї маски прямо в масиві
array[array < 0] = 0

print("3. Масив після заміни від'ємних чисел на нулі (показуємо перші 20 чисел):")
print(array[:20])
print("-" * 50)

# 4. Обчисліть середнє значення отриманого масиву.
mean_value = np.mean(array)

print(f"4. Середнє значення отриманого масиву: {mean_value}")